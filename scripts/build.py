def render_feed(issues):
    def pubdate(i):
        d = datetime.strptime(i["published"], "%Y-%m-%d").replace(hour=12, tzinfo=timezone.utc)
        return format_datetime(d)

    items = "\n".join(
        "    <item>\n"
        "      <title>{t}</title>\n"
        "      <link>{u}</link>\n"
        "      <guid isPermaLink=\"true\">{u}</guid>\n"
        "      <pubDate>{d}</pubDate>\n"
        "      <description>{desc}</description>\n"
        "    </item>".format(t=html.escape(i["title"]), u=i["url"], d=pubdate(i),
                             desc=html.escape(i["description"]))
        for i in reversed(issues)
    )
    return """<?xml version="1.0" encoding="utf-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>{title}</title>
    <link>{site}/</link>
    <atom:link href="{site}/feed.xml" rel="self" type="application/rss+xml"/>
    <description>{desc}</description>
    <language>en</language>
    <lastBuildDate>{last}</lastBuildDate>
{items}
  </channel>
</rss>
""".format(title=SITE_TITLE, site=SITE_URL, desc=html.escape(SITE_DESC),
           last=pubdate(issues[-1]), items=items)


def main():
    check = "--check" in sys.argv[1:]
    issues = load_issues()
    outputs = {"issues/%s/index.html" % i["slug"]: i["page"] for i in issues}
    outputs.update({
        "index.html": render_index(issues[-1]),
        "archive.html": render_archive(issues),
        "feed.xml": render_feed(issues),
    })
    stale = []
    for name, content in outputs.items():
        path = ROOT / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if check:
            stale.append(name)
        else:
            path.write_text(content, encoding="utf-8")
            print("wrote", name)
    if stale:
        sys.exit("out of date: %s. Run: python3 scripts/build.py" % ", ".join(stale))
    if check:
        print("generated files are up to date")


if __name__ == "__main__":
    main()
