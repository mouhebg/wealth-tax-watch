#!/usr/bin/env python3
"""Build the site from the per-issue sources.

Each issue lives in its own folder (issues/01/, issues/02/, ...) with two
hand-edited files: issue.json (structured data) and stories.html (prose).
This script renders issues/NN/index.html from them with templates/issue.html,
then generates index.html (latest issue), archive.html and feed.xml.
Run it after adding or changing an issue:

    python3 scripts/build.py          # write the generated files
    python3 scripts/build.py --check  # exit 1 if they are out of date (CI)

Standard library only, so it runs anywhere Python 3.8+ is installed.
"""
import html
import re
import sys
from datetime import datetime, timezone
from email.utils import format_datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from render_issue import render as render_issue  # noqa: E402

SITE_URL = "https://wealth-tax-watch.vercel.app"
SITE_TITLE = "Wealth Tax Watch"
SITE_DESC = ("A personal tracker of wealth tax developments around the world: proposals, "
             "public opinion and international tax cooperation, with a new issue every "
             "two weeks.")

ROOT = Path(__file__).resolve().parent.parent
GENERATED = "<!-- Generated by scripts/build.py from {src}. Edit the source, then rerun the script. -->\n"


def meta(page, attr, name):
    m = re.search(r'<meta %s="%s" content="([^"]*)"' % (attr, re.escape(name)), page)
    if not m:
        sys.exit("missing <meta %s=\"%s\">" % (attr, name))
    return html.unescape(m.group(1))


def load_issues():
    issues = []
    for src in sorted((ROOT / "issues").glob("*/issue.json")):
        path = src.parent / "index.html"
        page = render_issue(src.parent, SITE_URL)
        slug = path.parent.name
        issues.append({
            "slug": slug,
            "path": path,
            "page": page,
            "title": meta(page, "property", "og:title"),
            "description": meta(page, "name", "description"),
            "published": meta(page, "property", "article:published_time"),
            "url": "%s/issues/%s/" % (SITE_URL, slug),
        })
    if not issues:
        sys.exit("no issues found under issues/")
    return issues


def render_index(latest):
    # The root page is a copy of the latest issue, with links that climb out of
    # issues/NN/ rewritten to work from the site root. Its canonical URL stays
    # pointed at the issue's permanent address.
    page = latest["page"].replace('href="../../', 'href="').replace('src="../../', 'src="')
    return re.sub(r"<!-- Generated by scripts/build.py[^\n]*-->\n", GENERATED.format(
        src="issues/%s/issue.json and stories.html" % latest["slug"]).replace("\\", "\\\\"), page, count=1)


